// jobs.h - Phase 4.1: job orders data layer (jobs.csv + job_lines.csv).
//   jobs.csv     : job_no,opened,customer_id,vehicle_id,odometer,complaint,mechanic,status,closed,notes
//   job_lines.csv: job_no,line_no,kind,part_id,description,quantity,unit_price,labor_fee
//
// Rules of this layer (4.1 only stores and reads - validation is 4.2, status rules 4.3, audit 4.4):
//   * job_no is generated here: JO-<year>-<5 digits>, e.g. JO-2026-00001. The counter is per year and is taken
//     from the highest number already in jobs.csv, all inside the lock, so two requests can never get the same number.
//   * EVERY operation (read or write) takes an in-process mutex AND an OS file lock on <dir>/jobs.lock, then
//     re-reads the CSVs from disk. So two JobStore objects - or two running copies of the program - stay consistent.
//   * Writes go through util::writeFileAtomic (tmp file + rename): a crash never leaves a half-written CSV.
//   * Money is kept in whole centavos (long long), never double. The CSV shows it as "850.50".
#pragma once
#include <cstdint>
#include <mutex>
#include <optional>
#include <string>
#include <vector>

namespace jobs {

struct Job {
    std::string jobNo;          // generated by createJob (anything passed in is ignored)
    std::string opened;         // YYYY-MM-DD
    int customerId = 0, vehicleId = 0;
    long long odometer = 0;     // km
    std::string complaint, mechanic;
    std::string status = "Open";   // becomes an enum in 4.2
    std::string closed;         // YYYY-MM-DD, blank until Released
    std::string notes;
};

struct JobLine {
    std::string jobNo;
    int lineNo = 0;             // 1,2,3... inside one job; assigned by addLine
    std::string kind;           // "Part" or "Labor" (becomes an enum in 4.2)
    int partId = 0;             // 0 for Labor lines
    std::string description;
    int quantity = 1;
    long long unitPriceCents = 0;   // Part lines
    long long laborFeeCents = 0;    // Labor lines
};

// ---- small pure helpers (also used by the tests) ----
std::string centsToMoney(long long cents);                    // 85050 -> "850.50"
bool parseMoney(const std::string& s, long long& cents);      // "850.5" / "850.50" / "850" -> cents; no sign, max 2 decimals
std::string makeJobNo(int year, int seq);                     // (2026, 1) -> "JO-2026-00001"
bool parseJobNo(const std::string& s, int& year, int& seq);   // strict inverse of makeJobNo

// OS-level exclusive lock on a file (flock on Linux/macOS, LockFileEx on Windows). Released in the destructor.
class FileLock {
public:
    explicit FileLock(const std::string& path);
    ~FileLock();
    FileLock(const FileLock&) = delete;
    FileLock& operator=(const FileLock&) = delete;
    bool ok() const { return handle_ != -1; }
private:
    std::intptr_t handle_ = -1;
};

// Thread-safe and multi-process-safe. Methods that fail return a message ("" = success), like the other stores.
class JobStore {
public:
    explicit JobStore(const std::string& dir);

    // Creates a job with the next free job_no (returned in jobNoOut). A blank `opened` becomes today.
    std::string createJob(Job in, std::string& jobNoOut);
    // Replaces the stored job that has in.jobNo.
    std::string updateJob(const Job& in);
    std::optional<Job> findJob(const std::string& jobNo) const;
    std::vector<Job> allJobs() const;

    // Appends a line to an existing job; lineNoOut gets the new line_no.
    std::string addLine(const std::string& jobNo, JobLine in, int& lineNoOut);
    std::vector<JobLine> linesOf(const std::string& jobNo) const;
    std::vector<JobLine> allLines() const;

    // Non-empty when malformed / duplicate rows were skipped on the last read (originals are kept as *.bak).
    std::string warning() const;

private:
    struct Snapshot {
        std::vector<Job> jobs;
        std::vector<JobLine> lines;
    };
    Snapshot load() const;   // caller already holds the locks
    bool writeJobs(const std::vector<Job>& jobs) const;
    bool writeLines(const std::vector<JobLine>& lines) const;

    std::string jobsFile_, linesFile_, lockFile_;
    mutable std::mutex mu_;
    mutable std::string warning_;
};

}  // namespace jobs
